-- Areej Flask compatibility schema.
-- Intentionally isolated from the existing Supabase public schema.
-- Run this in Supabase SQL Editor before running the data migration script.

create schema if not exists areej_app;

create table if not exists areej_app.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  role text not null,
  display_name text not null
);

create table if not exists areej_app.courses (
  id bigint generated by default as identity primary key,
  name text not null,
  description text default '',
  created_at timestamptz default now()
);

create table if not exists areej_app.enrollments (
  id bigint generated by default as identity primary key,
  student_name text not null,
  age text,
  programme text not null,
  guardian_name text,
  contact text,
  location text,
  payment_proof text,
  status text default 'Pending review',
  created_at timestamptz default now()
);

create table if not exists areej_app.messages (
  id bigint generated by default as identity primary key,
  sender_id bigint not null,
  recipient_id bigint not null,
  body text default '',
  is_read integer default 0,
  attachment_name text default '',
  attachment_path text default '',
  attachment_type text default '',
  created_at timestamptz default now()
);

create table if not exists areej_app.classes (
  id bigint generated by default as identity primary key,
  course_id bigint,
  teacher_id bigint,
  name text not null,
  description text default '',
  schedule text default '',
  meeting_url text default '',
  channel text default '',
  created_at timestamptz default now()
);

create table if not exists areej_app.enrollments_academic (
  id bigint generated by default as identity primary key,
  student_id bigint not null,
  class_id bigint not null,
  enrolled_at timestamptz default now(),
  unique(student_id, class_id)
);

create table if not exists areej_app.attendance (
  id bigint generated by default as identity primary key,
  class_id bigint not null,
  student_id bigint not null,
  lesson_date text not null,
  status text default 'present',
  recorded_by bigint,
  unique(class_id, student_id, lesson_date)
);

create table if not exists areej_app.assignments (
  id bigint generated by default as identity primary key,
  class_id bigint not null,
  title text not null,
  instructions text default '',
  due_date text default '',
  created_at timestamptz default now()
);

create table if not exists areej_app.assignment_submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null,
  student_id bigint not null,
  content text default '',
  file_name text default '',
  file_path text default '',
  submitted_at timestamptz default now(),
  unique(assignment_id, student_id)
);

create table if not exists areej_app.results (
  id bigint generated by default as identity primary key,
  class_id bigint not null,
  student_id bigint not null,
  assessment text not null,
  score double precision not null,
  maximum_score double precision default 100,
  feedback text default '',
  created_at timestamptz default now()
);

create table if not exists areej_app.learning_materials (
  id bigint generated by default as identity primary key,
  class_id bigint,
  title text not null,
  file_name text default '',
  file_path text default '',
  url text default '',
  created_at timestamptz default now()
);

create table if not exists areej_app.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  audience text default 'all',
  created_at timestamptz default now()
);

create table if not exists areej_app.parent_links (
  parent_id bigint not null,
  student_id bigint not null,
  primary key(parent_id, student_id)
);

create index if not exists idx_areej_messages_recipient_unread
  on areej_app.messages(recipient_id, is_read);
create index if not exists idx_areej_messages_created
  on areej_app.messages(created_at);
create index if not exists idx_areej_classes_teacher
  on areej_app.classes(teacher_id);
create index if not exists idx_areej_enrollments_created
  on areej_app.enrollments(created_at);
