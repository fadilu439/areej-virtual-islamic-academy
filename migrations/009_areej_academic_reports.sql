-- AREEJ Academic Reports and Assignment Review
ALTER TABLE areej_app.assignment_submissions ADD COLUMN IF NOT EXISTS score numeric;
ALTER TABLE areej_app.assignment_submissions ADD COLUMN IF NOT EXISTS feedback text NOT NULL DEFAULT '';
ALTER TABLE areej_app.assignment_submissions ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'submitted';
ALTER TABLE areej_app.assignment_submissions ADD COLUMN IF NOT EXISTS reviewed_by bigint;
ALTER TABLE areej_app.assignment_submissions ADD COLUMN IF NOT EXISTS reviewed_at timestamptz;

CREATE TABLE IF NOT EXISTS areej_app.academic_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_type text NOT NULL CHECK (report_type IN ('daily','weekly','student_progress')),
  class_id bigint NOT NULL REFERENCES areej_app.classes(id) ON DELETE RESTRICT,
  staff_id bigint NOT NULL REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  student_id bigint REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  report_date date NOT NULL,
  week_start date,
  week_end date,
  topic text NOT NULL DEFAULT '',
  duration_minutes integer NOT NULL DEFAULT 0 CHECK (duration_minutes >= 0 AND duration_minutes <= 240),
  attendance_count integer NOT NULL DEFAULT 0 CHECK (attendance_count >= 0),
  progress_notes text NOT NULL DEFAULT '',
  challenges text NOT NULL DEFAULT '',
  next_steps text NOT NULL DEFAULT '',
  score numeric,
  maximum_score numeric,
  teacher_comments text NOT NULL DEFAULT '',
  recommendations text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'submitted' CHECK (status IN ('draft','submitted','approved','rejected')),
  reviewer_id bigint REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  reviewed_at timestamptz,
  review_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((score IS NULL AND maximum_score IS NULL) OR (score >= 0 AND maximum_score > 0 AND score <= maximum_score)),
  CHECK (report_type <> 'student_progress' OR student_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS academic_reports_staff_date_idx ON areej_app.academic_reports(staff_id, report_date DESC);
CREATE INDEX IF NOT EXISTS academic_reports_class_date_idx ON areej_app.academic_reports(class_id, report_date DESC);
CREATE INDEX IF NOT EXISTS academic_reports_status_idx ON areej_app.academic_reports(status, report_date DESC);

ALTER TABLE areej_app.academic_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE areej_app.academic_reports FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE areej_app.academic_reports TO service_role;
