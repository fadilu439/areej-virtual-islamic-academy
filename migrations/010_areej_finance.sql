-- AREEJ private, optional manual finance workflows. No fee amounts are seeded.
CREATE TABLE IF NOT EXISTS areej_app.finance_settings (
  id integer PRIMARY KEY CHECK (id=1),
  currency char(3) NOT NULL DEFAULT 'NGN',
  fees_enabled boolean NOT NULL DEFAULT false,
  updated_by bigint REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS areej_app.fee_plans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  programme text NOT NULL DEFAULT '',
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  currency char(3) NOT NULL,
  billing_cycle text NOT NULL DEFAULT 'one_time' CHECK (billing_cycle IN ('one_time','monthly','termly','custom')),
  is_active boolean NOT NULL DEFAULT true,
  created_by bigint NOT NULL REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS fee_plans_active_idx ON areej_app.fee_plans(is_active,title);

CREATE TABLE IF NOT EXISTS areej_app.invoices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id bigint NOT NULL REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  fee_plan_id bigint REFERENCES areej_app.fee_plans(id) ON DELETE SET NULL,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  currency char(3) NOT NULL,
  due_date date,
  status text NOT NULL DEFAULT 'unpaid' CHECK (status IN ('unpaid','partial','paid','cancelled')),
  created_by bigint NOT NULL REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS areej_app.payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id bigint NOT NULL REFERENCES areej_app.invoices(id) ON DELETE RESTRICT,
  student_id bigint NOT NULL REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  method text NOT NULL DEFAULT 'manual_transfer' CHECK (method='manual_transfer'),
  reference text NOT NULL DEFAULT '',
  proof_path text NOT NULL,
  proof_name text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','rejected')),
  reviewed_by bigint REFERENCES areej_app.users(id) ON DELETE RESTRICT,
  reviewed_at timestamptz,
  receipt_number text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS invoices_student_created_idx ON areej_app.invoices(student_id,created_at DESC);
CREATE INDEX IF NOT EXISTS payments_invoice_status_idx ON areej_app.payments(invoice_id,status);
CREATE INDEX IF NOT EXISTS payments_student_created_idx ON areej_app.payments(student_id,created_at DESC);
ALTER TABLE areej_app.finance_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE areej_app.fee_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE areej_app.invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE areej_app.payments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE areej_app.finance_settings, areej_app.fee_plans, areej_app.invoices, areej_app.payments FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE areej_app.finance_settings, areej_app.fee_plans, areej_app.invoices, areej_app.payments TO service_role;
