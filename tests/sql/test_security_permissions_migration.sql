-- Create future objects under both owners to prove default ACLs are safe.
CREATE TABLE public.future_postgres_table (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
CREATE FUNCTION public.future_postgres_function()
RETURNS integer LANGUAGE sql AS 'SELECT 1';

GRANT CREATE ON SCHEMA public TO supabase_admin;
SET ROLE supabase_admin;
CREATE TABLE public.future_supabase_admin_table (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
CREATE FUNCTION public.future_supabase_admin_function()
RETURNS integer LANGUAGE sql AS 'SELECT 1';
RESET ROLE;

DO $$
DECLARE
    client_role text;
    object_name text;
BEGIN
    FOREACH client_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        FOREACH object_name IN ARRAY ARRAY['public.security_probe'] LOOP
            IF has_table_privilege(client_role, object_name, 'TRUNCATE')
               OR has_table_privilege(client_role, object_name, 'REFERENCES')
               OR has_table_privilege(client_role, object_name, 'TRIGGER')
               OR has_table_privilege(client_role, object_name, 'MAINTAIN') THEN
                RAISE EXCEPTION 'Dangerous table privilege remains for % on %', client_role, object_name;
            END IF;
        END LOOP;

        IF NOT has_table_privilege(client_role, 'public.security_probe', 'SELECT')
           OR NOT has_table_privilege(client_role, 'public.security_probe', 'INSERT') THEN
            RAISE EXCEPTION 'Expected existing CRUD grants were not preserved for %', client_role;
        END IF;

        IF has_sequence_privilege(client_role, 'public.security_probe_id_seq', 'USAGE') THEN
            RAISE EXCEPTION 'Client sequence privilege remains for %', client_role;
        END IF;
        IF has_function_privilege(client_role, 'public.security_probe_fn()', 'EXECUTE') THEN
            RAISE EXCEPTION 'Existing public function remains executable by %', client_role;
        END IF;
        IF has_schema_privilege(client_role, 'areej_app', 'USAGE') THEN
            RAISE EXCEPTION 'Compatibility schema is accessible to %', client_role;
        END IF;
        IF has_table_privilege(client_role, 'areej_app.private_probe', 'SELECT') THEN
            RAISE EXCEPTION 'Compatibility table is accessible to %', client_role;
        END IF;

        FOREACH object_name IN ARRAY ARRAY[
            'public.future_postgres_table',
            'public.future_supabase_admin_table'
        ] LOOP
            IF has_table_privilege(client_role, object_name, 'SELECT')
               OR has_table_privilege(client_role, object_name, 'INSERT')
               OR has_table_privilege(client_role, object_name, 'TRUNCATE') THEN
                RAISE EXCEPTION 'Unsafe default table privileges for % on %', client_role, object_name;
            END IF;
        END LOOP;

        IF has_sequence_privilege(client_role, 'public.future_postgres_table_id_seq', 'USAGE')
           OR has_sequence_privilege(client_role, 'public.future_supabase_admin_table_id_seq', 'USAGE') THEN
            RAISE EXCEPTION 'Unsafe default sequence privileges for %', client_role;
        END IF;
        IF has_function_privilege(client_role, 'public.future_postgres_function()', 'EXECUTE')
           OR has_function_privilege(client_role, 'public.future_supabase_admin_function()', 'EXECUTE') THEN
            RAISE EXCEPTION 'Unsafe default function privileges for %', client_role;
        END IF;
    END LOOP;
END
$$;
